-- ---------------------------------------------------------------
-- 3. PATIENTS (রোগীদের তালিকা ও হিস্ট্রি)
-- ---------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.patients (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    phone TEXT NOT NULL,
    age INT,
    gender TEXT,
    address TEXT,
    medical_history TEXT,
    allergies TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

CREATE INDEX IF NOT EXISTS idx_patients_phone ON public.patients(phone);
CREATE INDEX IF NOT EXISTS idx_patients_name ON public.patients(name);

ALTER TABLE public.patients ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Allow full access to patients" ON public.patients;
CREATE POLICY "Allow full access to patients"
    ON public.patients FOR ALL
    USING (true)
    WITH CHECK (true);

-- ---------------------------------------------------------------
-- 4. APPOINTMENTS (অ্যাপয়েন্টমেন্ট ও শিডিউল)
-- ---------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.appointments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id BIGINT NOT NULL REFERENCES public.patients(id) ON DELETE CASCADE,
    doctor_id BIGINT REFERENCES public.profiles(id) ON DELETE SET NULL,
    appointment_date TIMESTAMPTZ NOT NULL,
    status TEXT NOT NULL DEFAULT 'waiting' CHECK (status IN ('waiting', 'completed', 'cancelled')),
    note TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

CREATE INDEX IF NOT EXISTS idx_appointments_date ON public.appointments(appointment_date);
CREATE INDEX IF NOT EXISTS idx_appointments_patient ON public.appointments(patient_id);

ALTER TABLE public.appointments ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Allow full access to appointments" ON public.appointments;
CREATE POLICY "Allow full access to appointments"
    ON public.appointments FOR ALL
    USING (true)
    WITH CHECK (true);

-- ---------------------------------------------------------------
-- 5. TREATMENTS (চিকিৎসা ও ডেন্টাল প্রসিডিউর রেকর্ড)
-- ---------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.treatments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id BIGINT NOT NULL REFERENCES public.patients(id) ON DELETE CASCADE,
    doctor_id BIGINT REFERENCES public.profiles(id) ON DELETE SET NULL,
    tooth_number TEXT,
    procedure TEXT NOT NULL,
    cost NUMERIC(12, 2) NOT NULL DEFAULT 0.00,
    date TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

CREATE INDEX IF NOT EXISTS idx_treatments_patient ON public.treatments(patient_id);

ALTER TABLE public.treatments ENABLE ROW LEVEL SECURITY;

