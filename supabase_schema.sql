-- ---------------------------------------------------------------
-- 2. PROFILES (ডাক্তার ও স্টাফদের প্রোফাইল - সম্পূর্ণ সাধারণ টেবিল)
--    কোনো auth.users বা Supabase Auth নির্ভরতা নেই।
--    Supabase Table Editor থেকে সরাসরি ডাক্তার বা স্টাফ যোগ ও এডিট করা যাবে।
--    অ্যাপে Phone অথবা Email এবং Password দিয়ে লগইন করা যাবে।
-- ---------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.profiles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name TEXT NOT NULL,
    role TEXT NOT NULL DEFAULT 'dentist' CHECK (role IN ('dentist', 'receptionist', 'admin')),
    email TEXT,
    phone TEXT,
    password TEXT NOT NULL DEFAULT '123456',
    qualification TEXT DEFAULT 'BDS, Dental Surgeon',
    is_active BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

CREATE INDEX IF NOT EXISTS idx_profiles_email ON public.profiles(email);
CREATE INDEX IF NOT EXISTS idx_profiles_phone ON public.profiles(phone);

ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Allow full access to profiles" ON public.profiles;
CREATE POLICY "Allow full access to profiles"
    ON public.profiles FOR ALL
    USING (true)
    WITH CHECK (true);

